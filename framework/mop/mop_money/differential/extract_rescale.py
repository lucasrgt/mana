"""Builds csharp/Program.cs with PubPauta's Rescale copied verbatim from its source file.

Usage: python3 -I extract_rescale.py <path to pauta-web-monorepo>
"""
import pathlib
import sys

repo = pathlib.Path(sys.argv[1])
module = repo / "api/src/Pauta.Api/Modules/MediaAuthorizations"
plan = (module / "MediaAuthorizationBillingPlan.cs").read_text().splitlines()
record = next(
    line for line in (module / "MediaAuthorizationInstallmentPlan.cs").read_text().splitlines()
    if line.startswith("public sealed record MediaAuthorizationInstallmentInput(")
)

start = next(i for i, line in enumerate(plan) if "IReadOnlyList<MediaAuthorizationInstallmentInput> Rescale(" in line)
end = next(i for i in range(start, len(plan)) if plan[i] == "    }")
# The one change: `private` becomes `internal` so the harness can call it.
method = "\n".join(plan[start : end + 1]).replace("private static", "internal static", 1)

program = f"""// Generated by extract_rescale.py from {module.relative_to(repo)}/MediaAuthorizationBillingPlan.cs
// lines {start + 1}-{end + 1}, with `private` made `internal`. Do not edit: rerun the script.
using System.Globalization;

{record}

static class Pauta
{{
{method}
}}

static class Harness
{{
    static void Main()
    {{
        string? line;
        while ((line = Console.ReadLine()) != null)
        {{
            var fields = line.Split(';');
            var total = long.Parse(fields[0], CultureInfo.InvariantCulture);
            var plan = fields[1].Split(',')
                .Select(v => new MediaAuthorizationInstallmentInput(new DateOnly(2026, 1, 1), long.Parse(v, CultureInfo.InvariantCulture)))
                .ToList();
            try
            {{
                var result = Pauta.Rescale(plan, total);
                Console.WriteLine(string.Join(",", result.Select(i => i.ValueInCents.ToString(CultureInfo.InvariantCulture))));
            }}
            catch (Exception e)
            {{
                Console.WriteLine("!" + e.GetType().Name);
            }}
        }}
    }}
}}
"""
(pathlib.Path(__file__).parent / "csharp/Program.cs").write_text(program)
print(f"Rescale: lines {start + 1}-{end + 1}")
